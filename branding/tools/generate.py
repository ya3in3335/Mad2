#!/usr/bin/env python3
"""Regenerates every VELTRIX brand asset from symbol.py + wordmark.py.

Usage: python3 branding/tools/generate.py   (requires: pip install cairosvg pillow)
Outputs: branding/logo (SVG sources), branding/exports (PNG/ICO/BMP), and copies into the app projects.
"""
import io
import os
import shutil
import sys

import cairosvg
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import symbol as S  # noqa: E402
import wordmark as W  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
LOGO = os.path.join(ROOT, "branding", "logo")
EXPORTS = os.path.join(ROOT, "branding", "exports")
TAGLINE = "POWERING BUSINESS INTELLIGENCE"


def write(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)


def png(svg, size, path=None, height=None):
    data = cairosvg.svg2png(bytestring=svg.encode("utf-8"), output_width=size, output_height=height)
    if path:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as f:
            f.write(data)
    return data


def horizontal(text_color, os_color, mode, background=None):
    w, g = W.wordmark_group(text_color, os_color)
    scale = 0.9
    gap = 60
    sym = 300
    total_w = sym + gap + w * scale + 40
    height = 340
    bg = f'<rect width="{total_w}" height="{height}" fill="{background}"/>' if background else ""
    tag = W.layout(TAGLINE)
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {total_w:.0f} {height}" width="{total_w:.0f}" height="{height}" role="img" aria-label="VELTRIX OS">
  {S.defs()}
  {bg}
  <g transform="translate(20 20) scale({sym/512})">{S.symbol_group(mode)}</g>
  <g transform="translate({20 + sym + gap} 112) scale({scale})">{g}</g>
  <g transform="translate({20 + sym + gap} 236) scale(0.24)" fill="none" stroke="{os_color if mode == 'color' else text_color}" stroke-width="{W.STROKE}" stroke-linecap="square" opacity="0.85">{tag[1]}</g>
</svg>
"""


def vertical(text_color, os_color, mode, background=None):
    w, g = W.wordmark_group(text_color, os_color)
    width = max(w * 0.8 + 80, 520)
    height = 640
    bg = f'<rect width="{width}" height="{height}" fill="{background}"/>' if background else ""
    tw, tg = W.layout(TAGLINE)
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width:.0f} {height}" width="{width:.0f}" height="{height}" role="img" aria-label="VELTRIX OS">
  {S.defs()}
  {bg}
  <g transform="translate({(width - 380) / 2} 20) scale({380/512})">{S.symbol_group(mode)}</g>
  <g transform="translate({(width - w * 0.8) / 2} 450) scale(0.8)">{g}</g>
  <g transform="translate({(width - tw * 0.2) / 2} 570) scale(0.2)" fill="none" stroke="{os_color if mode == 'color' else text_color}" stroke-width="{W.STROKE}" stroke-linecap="square" opacity="0.85">{tg}</g>
</svg>
"""


def android_vector(mode):
    """Android VectorDrawable (108dp adaptive foreground with 66dp safe zone, or 24dp notification glyph)."""
    def pts(p): return "M" + " L".join(f"{x:.1f},{y:.1f}" for x, y in p) + " Z"
    (x1, y1), (x2, y2) = S.TRACE
    if mode == "notification":
        # Single-color silhouette; Android tints it. Trace drawn as cut-out via even-odd is not supported reliably, so omit.
        return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by branding/tools/generate.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="512" android:viewportHeight="512">
    <path android:fillColor="#FFFFFFFF" android:pathData="{pts(S.LEFT)}"/>
    <path android:fillColor="#FFFFFFFF" android:pathData="{pts(S.RIGHT)}"/>
    <path android:fillColor="#FFFFFFFF" android:pathData="M{S.CORE[0]},{S.CORE[1]} m-{S.CORE_R},0 a{S.CORE_R},{S.CORE_R} 0 1,0 {2*S.CORE_R},0 a{S.CORE_R},{S.CORE_R} 0 1,0 -{2*S.CORE_R},0"/>
</vector>
"""
    # Adaptive icon foreground: symbol scaled into the central safe zone (viewport 512 → 108dp, symbol occupies ~60%).
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by branding/tools/generate.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp" android:viewportWidth="512" android:viewportHeight="512">
  <group android:scaleX="0.6" android:scaleY="0.6" android:pivotX="256" android:pivotY="256">
    <path android:pathData="{pts(S.LEFT)}">
      <aapt:attr name="android:fillColor">
        <gradient android:type="linear" android:startX="84" android:startY="104" android:endX="260" android:endY="432">
          <item android:offset="0" android:color="#FF3478FF"/><item android:offset="1" android:color="#FF00D9FF"/>
        </gradient>
      </aapt:attr>
    </path>
    <path android:pathData="{pts(S.RIGHT)}">
      <aapt:attr name="android:fillColor">
        <gradient android:type="linear" android:startX="428" android:startY="104" android:endX="300" android:endY="336">
          <item android:offset="0" android:color="#FF765BFF"/><item android:offset="1" android:color="#FF3478FF"/>
        </gradient>
      </aapt:attr>
    </path>
    <path android:strokeColor="#D9F5F8FF" android:strokeWidth="6" android:strokeLineCap="round" android:pathData="M{x1},{y1} L{x2},{y2}"/>
    <path android:fillColor="#D9F5F8FF" android:pathData="M{x1},{y1} m-{S.NODE_R},0 a{S.NODE_R},{S.NODE_R} 0 1,0 {2*S.NODE_R},0 a{S.NODE_R},{S.NODE_R} 0 1,0 -{2*S.NODE_R},0"/>
    <path android:fillColor="#D9F5F8FF" android:pathData="M{x2},{y2} m-{S.NODE_R},0 a{S.NODE_R},{S.NODE_R} 0 1,0 {2*S.NODE_R},0 a{S.NODE_R},{S.NODE_R} 0 1,0 -{2*S.NODE_R},0"/>
    <path android:fillColor="#FF00D9FF" android:pathData="M{S.CORE[0]},{S.CORE[1]} m-{S.CORE_R},0 a{S.CORE_R},{S.CORE_R} 0 1,0 {2*S.CORE_R},0 a{S.CORE_R},{S.CORE_R} 0 1,0 -{2*S.CORE_R},0"/>
  </group>
</vector>
"""


def main():
    # ---- SVG sources ----
    sources = {
        "veltrix-symbol.svg": S.symbol_svg("color"),
        "veltrix-symbol-mono-light.svg": S.symbol_svg("mono-light"),
        "veltrix-symbol-mono-dark.svg": S.symbol_svg("mono-dark"),
        "veltrix-app-icon.svg": S.symbol_svg("color", background=S.NAVY, radius=112, padding=56),
        "veltrix-splash-emblem.svg": S.symbol_svg("color"),
        "veltrix-logo-horizontal-dark.svg": horizontal(S.WHITE, S.CYAN, "color"),
        "veltrix-logo-horizontal-light.svg": horizontal(S.NAVY, S.BLUE, "color"),
        "veltrix-logo-vertical-dark.svg": vertical(S.WHITE, S.CYAN, "color"),
        "veltrix-logo-vertical-light.svg": vertical(S.NAVY, S.BLUE, "color"),
        "veltrix-logo-mono-light.svg": horizontal(S.WHITE, S.WHITE, "mono-light"),
        "veltrix-logo-mono-dark.svg": horizontal(S.NAVY, S.NAVY, "mono-dark"),
        "veltrix-logo-primary.svg": horizontal(S.WHITE, S.CYAN, "color", background=S.NAVY),
    }
    for name, svg in sources.items():
        write(os.path.join(LOGO, name), svg)

    # ---- PNG exports ----
    for size in [16, 24, 32, 48, 64, 128, 180, 192, 256, 512, 1024]:
        png(sources["veltrix-app-icon.svg"], size, os.path.join(EXPORTS, "png", f"app-icon-{size}.png"))
        png(sources["veltrix-symbol.svg"], size, os.path.join(EXPORTS, "png", f"symbol-{size}.png"))
    for name in ["veltrix-logo-horizontal-dark", "veltrix-logo-horizontal-light", "veltrix-logo-vertical-dark", "veltrix-logo-vertical-light", "veltrix-logo-primary"]:
        png(sources[name + ".svg"], 1200, os.path.join(EXPORTS, "png", name + ".png"))

    # ---- Windows ICO (application + tray) ----
    def ico(svg, sizes, path):
        imgs = [Image.open(io.BytesIO(png(svg, s))).convert("RGBA") for s in sizes]
        os.makedirs(os.path.dirname(path), exist_ok=True)
        imgs[-1].save(path, format="ICO", sizes=[(s, s) for s in sizes], append_images=imgs[:-1])
    ico(sources["veltrix-app-icon.svg"], [16, 24, 32, 48, 64, 128, 256], os.path.join(EXPORTS, "windows", "veltrix.ico"))
    ico(S.symbol_svg("mono-light"), [16, 20, 24, 32], os.path.join(EXPORTS, "windows", "veltrix-tray-dark.ico"))
    ico(S.symbol_svg("color"), [16, 20, 24, 32], os.path.join(EXPORTS, "windows", "veltrix-tray.ico"))
    ico(sources["veltrix-app-icon.svg"], [16, 32, 48], os.path.join(EXPORTS, "web", "favicon.ico"))
    shutil.copy(os.path.join(LOGO, "veltrix-app-icon.svg"), os.path.join(EXPORTS, "web", "icon.svg"))
    png(sources["veltrix-app-icon.svg"], 180, os.path.join(EXPORTS, "web", "apple-touch-icon.png"))

    # ---- Inno Setup wizard bitmaps (BMP, 24-bit) ----
    banner = f"""<svg xmlns="http://www.w3.org/2000/svg" width="164" height="314" viewBox="0 0 164 314">
  {S.defs()}<rect width="164" height="314" fill="{S.NAVY}"/>
  <rect y="250" width="164" height="64" fill="{S.NAVY2}"/>
  <g transform="translate(22 70) scale({120/512})">{S.symbol_group('color')}</g>
</svg>"""
    for name, svg, w, h in [("wizard-image.bmp", banner, 164, 314), ("wizard-small.bmp", S.symbol_svg("color", background=S.NAVY, padding=40), 55, 55)]:
        img = Image.open(io.BytesIO(png(svg, w, height=h))).convert("RGB")
        os.makedirs(os.path.join(EXPORTS, "installer"), exist_ok=True)
        img.save(os.path.join(EXPORTS, "installer", name), format="BMP")

    # ---- Android ----
    densities = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
    round_icon = S.symbol_svg("color", background=S.NAVY, radius=256, padding=96)
    for d, s in densities.items():
        png(sources["veltrix-app-icon.svg"], s, os.path.join(EXPORTS, "android", f"mipmap-{d}", "ic_launcher.png"))
        png(round_icon, s, os.path.join(EXPORTS, "android", f"mipmap-{d}", "ic_launcher_round.png"))
    write(os.path.join(EXPORTS, "android", "drawable", "ic_launcher_foreground.xml"), android_vector("adaptive"))
    write(os.path.join(EXPORTS, "android", "drawable", "ic_notification.xml"), android_vector("notification"))
    write(os.path.join(EXPORTS, "android", "drawable", "ic_veltrix_emblem.xml"), android_vector("adaptive").replace('android:scaleX="0.6" android:scaleY="0.6"', 'android:scaleX="1" android:scaleY="1"'))
    write(os.path.join(EXPORTS, "android", "mipmap-anydpi-v26", "ic_launcher.xml"),
          '<?xml version="1.0" encoding="utf-8"?>\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
          '    <background android:drawable="@color/veltrix_navy"/>\n    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n'
          '    <monochrome android:drawable="@drawable/ic_notification"/>\n</adaptive-icon>\n')
    shutil.copy(os.path.join(EXPORTS, "android", "mipmap-anydpi-v26", "ic_launcher.xml"), os.path.join(EXPORTS, "android", "mipmap-anydpi-v26", "ic_launcher_round.xml"))
    png(sources["veltrix-app-icon.svg"], 512, os.path.join(EXPORTS, "android", "play-store-icon-512.png"))

    # ---- Install into app projects (if present) ----
    installs = [
        (os.path.join(EXPORTS, "windows", "veltrix.ico"), os.path.join(ROOT, "apps", "windows", "Veltrix.Desktop", "Assets", "veltrix.ico")),
        (os.path.join(EXPORTS, "windows", "veltrix-tray.ico"), os.path.join(ROOT, "apps", "windows", "Veltrix.Desktop", "Assets", "veltrix-tray.ico")),
        (os.path.join(EXPORTS, "png", "symbol-256.png"), os.path.join(ROOT, "apps", "windows", "Veltrix.Desktop", "Assets", "symbol-256.png")),
        (os.path.join(EXPORTS, "installer", "wizard-image.bmp"), os.path.join(ROOT, "apps", "windows", "installer", "wizard-image.bmp")),
        (os.path.join(EXPORTS, "installer", "wizard-small.bmp"), os.path.join(ROOT, "apps", "windows", "installer", "wizard-small.bmp")),
        (os.path.join(EXPORTS, "web", "favicon.ico"), os.path.join(ROOT, "apps", "control-center", "src", "app", "favicon.ico")),
        (os.path.join(EXPORTS, "web", "icon.svg"), os.path.join(ROOT, "apps", "control-center", "public", "icon.svg")),
        (os.path.join(LOGO, "veltrix-symbol.svg"), os.path.join(ROOT, "apps", "control-center", "public", "veltrix-symbol.svg")),
    ]
    res = os.path.join(ROOT, "apps", "android", "app", "src", "main", "res")
    for d in densities:
        for n in ["ic_launcher.png", "ic_launcher_round.png"]:
            installs.append((os.path.join(EXPORTS, "android", f"mipmap-{d}", n), os.path.join(res, f"mipmap-{d}", n)))
    for n in ["ic_launcher_foreground.xml", "ic_notification.xml", "ic_veltrix_emblem.xml"]:
        installs.append((os.path.join(EXPORTS, "android", "drawable", n), os.path.join(res, "drawable", n)))
    for n in ["ic_launcher.xml", "ic_launcher_round.xml"]:
        installs.append((os.path.join(EXPORTS, "android", "mipmap-anydpi-v26", n), os.path.join(res, "mipmap-anydpi-v26", n)))
    for src, dst in installs:
        app_dir = dst.split(os.sep + "apps" + os.sep)[1].split(os.sep)[0]
        if os.path.isdir(os.path.join(ROOT, "apps", app_dir)):
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copy(src, dst)
    print("Brand assets generated.")


if __name__ == "__main__":
    main()
