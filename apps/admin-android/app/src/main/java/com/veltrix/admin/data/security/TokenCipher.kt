package com.veltrix.admin.data.security

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Authenticated encryption for small secrets (session tokens, profile). Implementations bind each ciphertext to a
 * caller-supplied context (the entry name) as AAD, so a ciphertext copied to another entry fails to decrypt.
 */
interface TokenCipher {
    fun encrypt(plain: ByteArray, context: ByteArray): ByteArray
    fun decrypt(packed: ByteArray, context: ByteArray): ByteArray
    /** Irreversibly destroys the key material (secure logout / wipe). A new key is created on next use. */
    fun destroyKey()
}

/**
 * AES-GCM framing shared by the Keystore implementation and the JVM tests:
 * `[version:1][iv:12][ciphertext+tag:n]`. The IV is always generated by the provider (never caller-chosen),
 * which Android Keystore enforces with randomized encryption.
 */
object AesGcm {
    const val VERSION: Byte = 1
    const val IV_LENGTH = 12
    const val TAG_BITS = 128
    private const val TRANSFORMATION = "AES/GCM/NoPadding"

    fun encrypt(key: SecretKey, plain: ByteArray, aad: ByteArray): ByteArray {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, key)
        cipher.updateAAD(aad)
        val ct = cipher.doFinal(plain)
        val iv = cipher.iv
        require(iv.size == IV_LENGTH) { "Unexpected IV length ${iv.size}" }
        return byteArrayOf(VERSION) + iv + ct
    }

    fun decrypt(key: SecretKey, packed: ByteArray, aad: ByteArray): ByteArray {
        require(packed.size > 1 + IV_LENGTH + TAG_BITS / 8) { "Ciphertext too short" }
        require(packed[0] == VERSION) { "Unsupported ciphertext version ${packed[0]}" }
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, key, GCMParameterSpec(TAG_BITS, packed, 1, IV_LENGTH))
        cipher.updateAAD(aad)
        return cipher.doFinal(packed, 1 + IV_LENGTH, packed.size - 1 - IV_LENGTH)
    }
}

/** AES-256-GCM key held in the Android Keystore (non-exportable, hardware-backed where available). */
class KeystoreTokenCipher(private val alias: String = ALIAS) : TokenCipher {

    @Synchronized
    private fun key(): SecretKey {
        val ks = KeyStore.getInstance(PROVIDER).apply { load(null) }
        (ks.getEntry(alias, null) as? KeyStore.SecretKeyEntry)?.let { return it.secretKey }
        val gen = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, PROVIDER)
        gen.init(
            KeyGenParameterSpec.Builder(alias, KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT)
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setRandomizedEncryptionRequired(true)
                .setKeySize(256)
                .build()
        )
        return gen.generateKey()
    }

    override fun encrypt(plain: ByteArray, context: ByteArray): ByteArray = AesGcm.encrypt(key(), plain, context)
    override fun decrypt(packed: ByteArray, context: ByteArray): ByteArray = AesGcm.decrypt(key(), packed, context)

    @Synchronized
    override fun destroyKey() {
        runCatching { KeyStore.getInstance(PROVIDER).apply { load(null) }.deleteEntry(alias) }
    }

    companion object {
        private const val PROVIDER = "AndroidKeyStore"
        const val ALIAS = "veltrix_admin_tokens_v1"
    }
}
