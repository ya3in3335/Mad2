BG = {"Dark": "07080B", "Light": "EEF0F4"}
def lum(h):
    c=[int(h[i:i+2],16)/255 for i in (0,2,4)]
    c=[x/12.92 if x<=0.03928 else ((x+0.055)/1.055)**2.4 for x in c]
    return 0.2126*c[0]+0.7152*c[1]+0.0722*c[2]
def cr(a,b):
    la,lb=sorted((lum(a),lum(b)),reverse=True); return (la+0.05)/(lb+0.05)
bad=False
for n,(d,l) in P.items():
    for t,p in (("Dark",d),("Light",l)):
        cs=[cr(p[3],g) for g in p[:3]]; ink=cr(p[4],BG[t])
        if min(cs)<4.5 or ink<4.5: bad=True
        print(f"{n:8}{t:6} on={min(cs):.2f} ink/bg={ink:.2f}")
if bad: print("CONTRAST FAIL"); sys.exit(1)
def a(alpha,h): return f"#{alpha}{h}"
def stops(*s): return "".join(f'\n        <GradientStop Color="{c}" Offset="{o}"/>' for c,o in s)
def lgb(key,sp,ep,*s): return f'    <LinearGradientBrush x:Key="{key}" StartPoint="{sp}" EndPoint="{ep}">{stops(*s)}\n    </LinearGradientBrush>\n'
def scb(key,c): return f'    <SolidColorBrush x:Key="{key}" Color="{c}"/>\n'
def rect(brush): return f'<GeometryDrawing><GeometryDrawing.Geometry><RectangleGeometry Rect="0,0,1,1"/></GeometryDrawing.Geometry><GeometryDrawing.Brush>{brush}</GeometryDrawing.Brush></GeometryDrawing>'
def radial(cx,r,c): return f'<RadialGradientBrush Center="{cx}" GradientOrigin="{cx}" RadiusX="{r}" RadiusY="{r}"><GradientStop Color="{c}" Offset="0"/><GradientStop Color="#00{c[3:]}" Offset="1"/></RadialGradientBrush>'
