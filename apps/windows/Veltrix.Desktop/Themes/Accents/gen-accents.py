        s+='    <DrawingBrush x:Key="Brush.backdrop" Stretch="Fill">\n        <DrawingBrush.Drawing>\n            <DrawingGroup>\n'+"".join(f"                {rect(x)}\n" for x in layers)+'            </DrawingGroup>\n        </DrawingBrush.Drawing>\n    </DrawingBrush>\n'
