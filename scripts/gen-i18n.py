#!/usr/bin/env python3
"""Generates platform resources from packages/localization/strings.json and packages/design-tokens/tokens.json.

Outputs:
  apps/android/app/src/main/res/values{,-fr,-ar}/strings.xml and values/colors.xml
  apps/android/app/src/main/java/com/veltrix/os/ui/theme/Tokens.kt
  apps/windows/Veltrix.Desktop/Localization/Strings.{en,fr,ar}.xaml and Themes/Colors.{Dark,Light}.xaml
  apps/control-center/src/i18n/{en,fr,ar}.json and src/app/tokens.css
"""
import json
import os
import re
from xml.sax.saxutils import escape

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
strings = json.load(open(os.path.join(ROOT, "packages/localization/strings.json"), encoding="utf-8"))
tokens = json.load(open(os.path.join(ROOT, "packages/design-tokens/tokens.json"), encoding="utf-8"))
LANGS = ["en", "fr", "ar"]
HEADER = "Generated by scripts/gen-i18n.py — do not edit."


def write(rel, content):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)


def android_key(k):
    return re.sub(r"[^a-zA-Z0-9_]", "_", k)


def android_value(v):
    v = escape(v).replace("'", "\\'").replace('"', '\\"')
    return re.sub(r"\{(\d+)\}", lambda m: f"%{int(m.group(1)) + 1}$s", v)


for lang in LANGS:
    folder = "values" if lang == "en" else f"values-{lang}"
    body = "\n".join(f'    <string name="{android_key(k)}">{android_value(v[lang])}</string>' for k, v in strings.items())
    write(f"apps/android/app/src/main/res/{folder}/strings.xml", f'<?xml version="1.0" encoding="utf-8"?>\n<!-- {HEADER} -->\n<resources>\n{body}\n</resources>\n')

    xaml = "\n".join(f'    <sys:String x:Key="{k}">{escape(v[lang])}</sys:String>' for k, v in strings.items())
    write(f"apps/windows/Veltrix.Desktop/Localization/Strings.{lang}.xaml",
          f'<!-- {HEADER} -->\n<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"\n'
          f'                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml" xmlns:sys="clr-namespace:System;assembly=mscorlib">\n{xaml}\n</ResourceDictionary>\n')

    write(f"apps/control-center/src/i18n/{lang}.json", json.dumps({k: v[lang] for k, v in strings.items()}, ensure_ascii=False, indent=1) + "\n")

# Colors
dark, light = tokens["color"]["dark"], tokens["color"]["light"]
write("apps/android/app/src/main/res/values/colors.xml",
      f'<?xml version="1.0" encoding="utf-8"?>\n<!-- {HEADER} -->\n<resources>\n' +
      "".join(f'    <color name="veltrix_dark_{k}">{v}</color>\n' for k, v in dark.items()) +
      "".join(f'    <color name="veltrix_light_{k}">{v}</color>\n' for k, v in light.items()) +
      f'    <color name="veltrix_navy">{dark["background"]}</color>\n</resources>\n')


def kt(c):
    return "Color(0xFF" + c.lstrip("#").upper() + ")"


write("apps/android/app/src/main/java/com/veltrix/os/ui/theme/Tokens.kt",
      f"// {HEADER}\npackage com.veltrix.os.ui.theme\n\nimport androidx.compose.ui.graphics.Color\n\n" +
      "object DarkTokens {\n" + "".join(f"    val {k} = {kt(v)}\n" for k, v in dark.items()) + "}\n\n" +
      "object LightTokens {\n" + "".join(f"    val {k} = {kt(v)}\n" for k, v in light.items()) + "}\n\n" +
      "object MotionTokens {\n" + "".join(f"    const val {k} = {v}\n" for k, v in tokens["motion"].items()) + "}\n")

for name, palette in [("Dark", dark), ("Light", light)]:
    write(f"apps/windows/Veltrix.Desktop/Themes/Colors.{name}.xaml",
          f'<!-- {HEADER} -->\n<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"\n'
          f'                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">\n' +
          "".join(f'    <Color x:Key="Color.{k}">{v}</Color>\n    <SolidColorBrush x:Key="Brush.{k}" Color="{v}"/>\n' for k, v in palette.items()) +
          "</ResourceDictionary>\n")

css = f"/* {HEADER} */\n:root {{\n" + "".join(f"  --vx-{k}: {v};\n" for k, v in light.items()) + \
      "".join(f"  --vx-radius-{k}: {v}px;\n" for k, v in tokens["radius"].items()) + "}\n" + \
      ".dark {\n" + "".join(f"  --vx-{k}: {v};\n" for k, v in dark.items()) + "}\n"
write("apps/control-center/src/app/tokens.css", css)
print(f"Generated {len(strings)} strings x {len(LANGS)} languages and theme tokens.")
